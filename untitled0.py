import pandas as pd

# Definer stiene til de faktiske UNSW_NB15-filene
train_path = '/content/unsw_nb15/UNSW_NB15_training-set.csv'
test_path = '/content/unsw_nb15/UNSW_NB15_testing-set.csv'

# Les inn filene
train_df = pd.read_csv(train_path)
test_df = pd.read_csv(test_path)

print(f"Treningssett: {train_df.shape[0]} rader, {train_df.shape[1]} kolonner")
print(f"Testsett: {test_df.shape[0]} rader, {test_df.shape[1]} kolonner\n")

# Vis kolonnenavn og de første radene i treningssettet
print("De første radene i treningssettet:")
display(train_df.head())

from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import classification_report, accuracy_score
import pandas as pd
import numpy as np

# 1. Separer features (X) og målet (y)
X_train = train_df.drop(columns=['id', 'attack_cat', 'label'])
y_train = train_df['label']

X_test = test_df.drop(columns=['id', 'attack_cat', 'label'])
y_test = test_df['label']

# Identifiser kategoriske kolonner
cat_cols = ['proto', 'service', 'state']

# 2. Slå sammen datasettene midlertidig for å sikre lik One-Hot Encoding
combined = pd.concat([X_train, X_test], keys=['train', 'test'])
combined_encoded = pd.get_dummies(combined, columns=cat_cols, drop_first=True)

# Splitt tilbake til tog og test
X_train_encoded = combined_encoded.xs('train')
X_test_encoded = combined_encoded.xs('test')

# 3. Skaler dataene
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train_encoded)
X_test_scaled = scaler.transform(X_test_encoded)

# 4. Initialiser og tren Logistic Regression-modellen
lr_model = LogisticRegression(max_iter=1000, random_state=42)
lr_model.fit(X_train_scaled, y_train)

# 5. Forutsi på testsettet
y_pred = lr_model.predict(X_test_scaled)

# 6. Vis resultater
print("Nøyaktighet (Accuracy):", accuracy_score(y_test, y_pred))
print("\nKlassifiseringsrapport:")
print(classification_report(y_test, y_pred))

# Vis de opprinnelige kolonnene som ble brukt som features (før One-Hot Encoding)
opprinnelige_features = list(X_train.columns)
print(f"Totalt antall opprinnelige features brukt: {len(opprinnelige_features)}")
print("\nDe brukte kolonnene:")
print(opprinnelige_features)

import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import confusion_matrix

# 1. Generer forvirringsmatrisen
cm = confusion_matrix(y_test, y_pred)

# 2. Visualiser matrisen med et varmekart (heatmap)
plt.figure(figsize=(8, 6))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
            xticklabels=['Normal (0)', 'Angrep (1)'],
            yticklabels=['Normal (0)', 'Angrep (1)'])

plt.title('Forvirringsmatrise - Logistic Regression (Alle features)')
plt.ylabel('Faktisk klasse')
plt.xlabel('Forutsagt klasse')
plt.show()

from sklearn.feature_selection import SelectKBest, f_classif

# 1. Velg de 15 beste egenskapene ved hjelp av SelectKBest (ANOVA F-verdi)
selector = SelectKBest(score_func=f_classif, k=15)
X_train_selected = selector.fit_transform(X_train_scaled, y_train)
X_test_selected = selector.transform(X_test_scaled)

# Få tak i navnene på de valgte kolonnene
selected_indices = selector.get_support(indices=True)
selected_features_names = X_train_encoded.columns[selected_indices]

print("De 15 valgte egenskapene etter Feature Selection:")
for idx, col in enumerate(selected_features_names, 1):
    print(f"{idx}. {col}")

# 2. Tren en ny Logistic Regression-modell på de utvalgte egenskapene
lr_model_selected = LogisticRegression(max_iter=1000, random_state=42)
lr_model_selected.fit(X_train_selected, y_train)

# 3. Gjør prediksjoner med den nye modellen
y_pred_selected = lr_model_selected.predict(X_test_selected)

# 4. Samle beregninger for sammenligningstabellen
from sklearn.metrics import precision_recall_fscore_support, accuracy_score

# Beregninger for LR med alle features
acc_all = accuracy_score(y_test, y_pred)
prec_all, rec_all, f1_all, _ = precision_recall_fscore_support(y_test, y_pred, average='binary')

# Beregninger for LR med utvalgte features
acc_sel = accuracy_score(y_test, y_pred_selected)
prec_sel, rec_sel, f1_sel, _ = precision_recall_fscore_support(y_test, y_pred_selected, average='binary')

# 5. Lag sammenligningstabellen
comparison_df = pd.DataFrame({
    'Metrikk': ['Nøyaktighet (Accuracy)', 'Precision (Klasse 1)', 'Recall (Klasse 1)', 'F1-Score (Klasse 1)'],
    'LR (Alle features)': [acc_all, prec_all, rec_all, f1_all],
    'LR (Utvalgte features)': [acc_sel, prec_sel, rec_sel, f1_sel]
})

display(comparison_df)